package com.itheima.ifdemo;

public class IfDemo4 {
    static void main() {
//        4. 判断布尔类型的变量
//            判断布尔类型的变量,直接把变量写在小括号中即可!!!
        boolean a = false;
        if (a) {
            System.out.println("a为true");
        }else {
            System.out.println("a为false");
        }
    }
}
